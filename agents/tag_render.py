"""Safe Terraform rendering for governed tag proposals."""

from __future__ import annotations

import hashlib
import json
import re

from contracts.capability_contract import Cloud, TagComplianceRequest, TagRef


class UnsafeIaCOwnershipError(RuntimeError):
    """A mutation was requested without a registered owning Terraform state."""


def _hcl_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def tag_remediation_slug(request: TagComplianceRequest) -> str:
    normalized = re.sub(r"[^a-z0-9_]", "_", request.resource_id.lower()).strip("_")
    digest = hashlib.sha256(f"{request.cloud.value}:{request.resource_id}".encode()).hexdigest()[:10]
    return f"tags_{normalized[:48] or 'resource'}_{digest}"


def _tags_block(tags: list[TagRef]) -> str:
    keys = [tag.key for tag in tags]
    if len(keys) != len(set(keys)):
        raise ValueError("duplicate tag keys are not allowed")
    lines = "\n".join(f"    {_hcl_string(tag.key)} = {_hcl_string(tag.value)}" for tag in tags)
    return "{\n" + lines + "\n  }"


def render_tag_remediation_diff(
    request: TagComplianceRequest,
    proposed_tags: list[TagRef],
    *,
    project_id: str | None = None,
) -> str:
    if request.cloud == Cloud.GCP:
        raise UnsafeIaCOwnershipError(
            "GCP bucket remediation is disabled until the bucket's owning Terraform state "
            "and resource address are registered; Aegis will not create or import a bucket implicitly"
        )
    if request.cloud != Cloud.AZURE:
        raise ValueError(f"unsupported cloud: {request.cloud!r}")

    slug = tag_remediation_slug(request)
    return (
        "# Generated by Aegis. Do not edit by hand.\n"
        f"module {_hcl_string(slug)} {{\n"
        f"  source              = {_hcl_string('../../modules/azure/resource_tags')}\n"
        f"  resource_group_name = {_hcl_string(request.resource_id)}\n"
        f"  tags                = {_tags_block(proposed_tags)}\n"
        "}\n"
    )
