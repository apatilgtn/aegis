"""Safe Terraform rendering for governed access proposals."""

from __future__ import annotations

import hashlib
import json
import re

from contracts.capability_contract import AccessGrantRequest
from contracts.entitlement_catalog import EntitlementCatalogEntry

_SAFE_MODULE_PATH = re.compile(r"^modules/(?:azure|gcp)/[a-z0-9][a-z0-9_/-]*$")


def _hcl_string(value: str) -> str:
    """JSON strings are valid HCL strings and correctly escape all input."""
    return json.dumps(value, ensure_ascii=False)


def _identifier(value: str, *, prefix: str) -> str:
    normalized = re.sub(r"[^a-z0-9_]", "_", value.lower()).strip("_")
    digest = hashlib.sha256(value.encode()).hexdigest()[:10]
    return f"{prefix}_{normalized[:48] or 'request'}_{digest}"


def _module_source(path: str) -> str:
    if not _SAFE_MODULE_PATH.fullmatch(path):
        raise ValueError(f"unsafe Terraform module path: {path!r}")
    return f"../../{path}"


def access_grant_slug(request: AccessGrantRequest, entry: EntitlementCatalogEntry) -> str:
    return _identifier(f"{entry.id}:{request.requester}", prefix="access")


def render_access_grant_diff(
    request: AccessGrantRequest,
    entry: EntitlementCatalogEntry,
    *,
    member_object_id: str | None = None,
    project_id: str | None = None,
) -> str:
    slug = access_grant_slug(request, entry)
    source = _module_source(entry.terraform_module)
    header = (
        "# Generated by Aegis. Do not edit by hand.\n"
        f"# Catalog entry: {re.sub(r'[^A-Za-z0-9_.-]', '_', entry.id)}\n"
        f"# TTL hours: {request.ttl_hours}\n\n"
    )

    if entry.resource_type == "entra_group":
        if not member_object_id:
            raise ValueError("entra_group diffs require a resolved member_object_id")
        body = (
            f"module {_hcl_string(slug)} {{\n"
            f"  source           = {_hcl_string(source)}\n"
            f"  group_object_id  = {_hcl_string(entry.resource_id)}\n"
            f"  member_object_id = {_hcl_string(member_object_id)}\n"
            "}\n"
        )
    elif entry.resource_type == "iam_binding":
        if not project_id:
            raise ValueError("iam_binding diffs require a resolved project_id")
        body = (
            f"module {_hcl_string(slug)} {{\n"
            f"  source  = {_hcl_string(source)}\n"
            f"  role    = {_hcl_string(entry.resource_id)}\n"
            f"  member  = {_hcl_string(f'user:{request.requester}')}\n"
            f"  project = {_hcl_string(project_id)}\n"
            "}\n"
        )
    else:
        raise ValueError(f"unsupported resource_type: {entry.resource_type!r}")

    return header + body
